const originalTextNodes=new WeakMap();
const originalPlaceholders=new WeakMap();

let currentLanguage=localStorage.getItem('catalyst_language')||'en';
let currentTheme=localStorage.getItem('catalyst_theme')||'light';

function localizedTitle(page){
  const map={
    dashboard:'dashboard',
    requisitions:'requisitions',
    jobs:'jobs',
    candidates:'candidates',
    pipeline:'pipeline',
    offers:'offersHires',
    onboarding:'onboarding',
    analytics:'peopleAnalytics'
  };
  return I18N[currentLanguage]?.[map[page]]||titles[page]||'Catalyst';
}

function translateValue(value){
  if(currentLanguage==='en') return value;
  return UI_TEXT_ES[value] ?? value;
}

function t(value){
  return translateValue(String(value ?? ''));
}

function translateRoot(root=document){
  if(!root) return;

  const walker=document.createTreeWalker(root,NodeFilter.SHOW_TEXT,{
    acceptNode(node){
      if(!node.nodeValue || !node.nodeValue.trim()) return NodeFilter.FILTER_REJECT;
      if(['SCRIPT','STYLE'].includes(node.parentElement?.tagName)) return NodeFilter.FILTER_REJECT;
      return NodeFilter.FILTER_ACCEPT;
    }
  });

  const nodes=[];
  while(walker.nextNode()) nodes.push(walker.currentNode);

  nodes.forEach(node=>{
    if(!originalTextNodes.has(node)) originalTextNodes.set(node,node.nodeValue);
    const original=originalTextNodes.get(node);
    const trimmed=original.trim();
    const leading=original.match(/^\s*/)?.[0]||'';
    const trailing=original.match(/\s*$/)?.[0]||'';

    if(currentLanguage==='es'){
      const translated=UI_TEXT_ES[trimmed];
      node.nodeValue=translated!==undefined ? leading+translated+trailing : original;
    }else{
      node.nodeValue=original;
    }
  });

  root.querySelectorAll?.('input[placeholder],textarea[placeholder]').forEach(el=>{
    if(!originalPlaceholders.has(el)) originalPlaceholders.set(el,el.getAttribute('placeholder')||'');
    const original=originalPlaceholders.get(el);
    el.setAttribute('placeholder',currentLanguage==='es' ? (PLACEHOLDER_ES[original]||original) : original);
  });
}

function updateGreeting(){
  const h1=document.querySelector('#dashboard .hero h1');
  if(!h1 || !currentEmpleado) return;
  const first=(currentEmpleado.nombre||currentEmpleado.nombre_completo||'').split(' ')[0]||'';
  h1.textContent=currentLanguage==='es' ? `Buenos días, ${first}.` : `Good morning, ${first}.`;
}

function applyPreferences(){
  document.documentElement.setAttribute('data-theme',currentTheme);
  document.documentElement.lang=currentLanguage;

  const themeButton=document.getElementById('themeToggle');
  if(themeButton) themeButton.textContent=currentTheme==='dark'?'☀':'☾';

  const languageButton=document.getElementById('langToggle');
  if(languageButton) languageButton.textContent=currentLanguage.toUpperCase();

  document.querySelectorAll('[data-i18n]').forEach(el=>{
    const value=I18N[currentLanguage]?.[el.dataset.i18n];
    if(value) el.textContent=value;
  });

  translateRoot(document);
  updateGreeting();

  const active=document.querySelector('.page.active')?.id||'dashboard';
  const topTitle=document.getElementById('topTitle');
  if(topTitle) topTitle.textContent=localizedTitle(active);

  if(typeof updateClock==='function') updateClock();
}

function toggleTheme(){
  currentTheme=currentTheme==='dark'?'light':'dark';
  localStorage.setItem('catalyst_theme',currentTheme);
  applyPreferences();
}

function toggleLanguageMenu(){
  document.getElementById('langPopover')?.classList.toggle('show');
}

function setLanguage(lang){
  currentLanguage=lang;
  localStorage.setItem('catalyst_language',lang);
  document.getElementById('langPopover')?.classList.remove('show');
  applyPreferences();

  // Dynamic table rows are regenerated with localized statuses on change.
  if(typeof loadRequisitions==='function' && currentEmpleado){
    loadRequisitions();
  }
}

document.addEventListener('click',e=>{
  if(!e.target.closest('.lang-menu')){
    document.getElementById('langPopover')?.classList.remove('show');
  }
});
